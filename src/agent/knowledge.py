def search_knowledge(query: str, limit: int = 3) -> dict:
    """关键词计分检索：返回最相关的条目（含出处），未命中时给出可用主题列表。"""
    q = (query or "").lower().strip()
    if not q:
        return {"error": "query 不能为空", "可用主题": [e["topic"] for e in KNOWLEDGE_ENTRIES]}
    scored = []
    for e in KNOWLEDGE_ENTRIES:
        score = 0
        if e["topic"].lower() in q or q in e["topic"].lower():
            score += 3
        for kw in e["keywords"]:
            if kw.lower() in q:
                score += 2
        for term in q.replace("，", " ").replace(",", " ").split():
            if term and (term in e["content"].lower() or term in e["topic"].lower()):
                score += 1
        if score > 0:
            scored.append((score, e))
    if not scored:
        return {"error": f"知识库未命中『{query}』",
                "可用主题": [e["topic"] for e in KNOWLEDGE_ENTRIES]}
    scored.sort(key=lambda x: -x[0])
    return {"命中条目": [
        {"主题": e["topic"], "要点": e["content"], "来源": e["source"]}
        for _, e in scored[:max(1, min(limit, 5))]
    ]}


